import { format } from "date-fns";
import { LearningNote } from "@/hooks/useLearningNotes";

interface NotesPrintViewProps {
  notes: LearningNote[];
  moduleTitle: string;
}

export function NotesPrintView({ notes, moduleTitle }: NotesPrintViewProps) {
  return (
    <div id="print-notes-container" className="hidden print:block text-black">
      <header className="border-b-2 border-black pb-4 mb-8">
        <h1 className="text-3xl font-bold">Guided Notes: {moduleTitle}</h1>
        <p className="text-sm text-gray-600 mt-2">
          Exported from LearnInk on {format(new Date(), "dd MMMM yyyy")}
        </p>
      </header>

      <div className="space-y-8">
        {notes.map((note) => (
          <div key={note.id} className="border-b border-gray-200 pb-6">
            <div className="flex justify-between items-start mb-2">
              <span className="text-xs font-bold uppercase tracking-wider text-gray-500">
                {note.highlighted_text ? "Highlighted Snippet" : "Note"}
              </span>
              <span className="text-xs text-gray-400">
                {format(new Date(note.created_at), "dd MMM yyyy, HH:mm")}
              </span>
            </div>

            {note.highlighted_text && (
              <div className="bg-gray-100 p-4 border-l-4 border-gray-300 italic text-sm mb-4">
                "{note.highlighted_text}"
              </div>
            )}

            <div className="text-base leading-relaxed whitespace-pre-wrap">
              {note.content}
            </div>
          </div>
        ))}
      </div>

      <footer className="mt-12 pt-4 border-t border-gray-200 text-center text-[13px] text-gray-400">
        Generated by LearnInk LMS - Your Interactive Learning Companion
      </footer>
    </div>
  );
}
